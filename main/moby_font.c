const uint8_t *moby_font_glyph(char ch)
{
    const unsigned char value = (unsigned char)ch;
    if (value >= MOBY_FONT_EXTRA_BASE && value < MOBY_FONT_EXTRA_BASE + MOBY_FONT_EXTRA_CELLS) {
        return EXTRA[value - MOBY_FONT_EXTRA_BASE];
    }
    return GLYPHS[value >= 0x20 && value <= 0x7e ? value - 0x20 : '?' - 0x20];
}

// The cell for a code point, or '?'. Every script keeps its own cells: nothing is transliterated or folded.
static unsigned char cell_for(uint32_t cp)
{
    if (cp >= 0x20 && cp <= 0x7e) {
        return (unsigned char)cp;
    }
    unsigned index = MOBY_FONT_EXTRA_CELLS;
    if (cp >= 0x0410 && cp <= 0x042f) {
        index = cp - 0x0410;
    } else if (cp == 0x0401) {
        index = 32;
    } else if (cp >= 0x0430 && cp <= 0x044f) {
        index = 33 + (cp - 0x0430);
    } else if (cp == 0x0451) {
        index = 65;
    } else if (cp == 0x040e || cp == 0x045e) {
        index = cp == 0x040e ? 66 : 67;
    } else if (cp == 0x049a || cp == 0x049b) {
        index = cp == 0x049a ? 68 : 69;
    } else if (cp == 0x0492 || cp == 0x0493) {
        index = cp == 0x0492 ? 70 : 71;
    } else if (cp == 0x04b2 || cp == 0x04b3) {
        index = cp == 0x04b2 ? 72 : 73;
    } else if (cp == 0x02bb || cp == 0x02bc || cp == 0x2018 || cp == 0x2019) {
        // The Uzbek turned comma (o, g and U+02BB) and the quotes people type for it.
        index = 74;
    }
    return index < MOBY_FONT_EXTRA_CELLS ? (unsigned char)(MOBY_FONT_EXTRA_BASE + index) : (unsigned char)'?';
}

size_t moby_font_decode(const char *utf8, char *cells, size_t max_cells)
{
    size_t count = 0;
    if (!cells || max_cells == 0) {
        return 0;
    }
    const unsigned char *p = (const unsigned char *)utf8;
    while (p && *p && count < max_cells) {
        uint32_t cp = *p++;
        unsigned extra = 0;
        unsigned char low = 0x80;
        unsigned char high = 0xbf;
        bool bad = false;
        if (cp < 0x80) {
            // ASCII control characters and DEL show as '?'.
        } else if (cp >= 0xc2 && cp <= 0xdf) {
            extra = 1;
            cp &= 0x1f;
        } else if (cp >= 0xe0 && cp <= 0xef) {
            extra = 2;
            low = cp == 0xe0 ? 0xa0 : 0x80;
            high = cp == 0xed ? 0x9f : 0xbf;
            cp &= 0x0f;
        } else if (cp >= 0xf0 && cp <= 0xf4) {
            extra = 3;
            low = cp == 0xf0 ? 0x90 : 0x80;
            high = cp == 0xf4 ? 0x8f : 0xbf;
            cp &= 0x07;
        } else {
            // A stray continuation byte, 0xc0, 0xc1, or 0xf5 and up.
            bad = true;
        }
        // A sequence that breaks off is one replacement, and the byte that broke it is read again.
        for (unsigned i = 0; i < extra && !bad; ++i) {
            if (*p >= low && *p <= high) {
                cp = (cp << 6) | (*p++ & 0x3fU);
                low = 0x80;
                high = 0xbf;
            } else {
                bad = true;
            }
        }
        cells[count++] = (char)(bad ? '?' : (char)cell_for(cp));
    }
    cells[count] = '\0';
    return count;
}
